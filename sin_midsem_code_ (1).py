import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score, f1_score, precision_score, recall_score
import torch
import torch.nn as nn

def sparse_to_tensor(sparse_mat):
    dense = sparse_mat.toarray() if hasattr(sparse_mat, 'toarray') else np.array(sparse_mat)
    return torch.FloatTensor(dense)

def prepare_tensors(hin):
    news_feat    = sparse_to_tensor(hin['news_features'])
    creator_feat = sparse_to_tensor(hin['creator_features'])
    subject_feat = torch.FloatTensor(hin['subject_features'])
    adj_ca       = torch.FloatTensor(hin['adj_ca'].toarray())
    adj_as       = torch.FloatTensor(hin['adj_as'].toarray())
    labels       = torch.LongTensor(hin['labels'])
    return news_feat, creator_feat, subject_feat, adj_ca, adj_as, labels


def run_experiment(hin, dataset_name, train_ratio=0.8, epochs=100, lr=0.005):
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    print(f"\n{'='*50}")
    print(f"Dataset: {dataset_name} | Train ratio: {train_ratio} | Device: {device}")
    print('='*50)

    news_feat, creator_feat, subject_feat, adj_ca, adj_as, labels = prepare_tensors(hin)

    n = len(labels)
    indices = np.arange(n)
    train_idx, temp_idx = train_test_split(
        indices, train_size=train_ratio, stratify=labels.numpy(), random_state=42
    )
    val_idx, test_idx = train_test_split(
        temp_idx, test_size=0.5, stratify=labels.numpy()[temp_idx], random_state=42
    )

    # ── Build model (no n_heads argument) ──────────────────────────
    model = HGAT(
        dim_news    = news_feat.size(1),
        dim_creator = creator_feat.size(1),
        dim_subject = subject_feat.size(1),
        hidden_dim  = 64,
        n_classes   = 2
    ).to(device)

    optimizer = torch.optim.Adam(model.parameters(), lr=lr, weight_decay=5e-4)
    criterion = nn.CrossEntropyLoss()

    news_feat    = news_feat.to(device)
    creator_feat = creator_feat.to(device)
    subject_feat = subject_feat.to(device)
    adj_ca       = adj_ca.to(device)
    adj_as       = adj_as.to(device)
    labels       = labels.to(device)

    best_val_acc = 0
    best_state   = None

    for epoch in range(1, epochs + 1):
        model.train()
        optimizer.zero_grad()
        logits = model(news_feat, creator_feat, subject_feat, adj_ca, adj_as)
        loss   = criterion(logits[train_idx], labels[train_idx])
        loss.backward()
        optimizer.step()

        if epoch % 10 == 0:
            model.eval()
            with torch.no_grad():
                val_logits = model(news_feat, creator_feat, subject_feat, adj_ca, adj_as)
                preds      = val_logits.argmax(dim=1).cpu().numpy()
                val_acc    = accuracy_score(labels.cpu().numpy()[val_idx], preds[val_idx])

            if val_acc > best_val_acc:
                best_val_acc = val_acc
                best_state   = {k: v.clone() for k, v in model.state_dict().items()}

            print(f"  Epoch {epoch:3d} | Loss: {loss.item():.4f} | Val Acc: {val_acc:.4f}")

    if best_state:
        model.load_state_dict(best_state)

    model.eval()
    with torch.no_grad():
        logits = model(news_feat, creator_feat, subject_feat, adj_ca, adj_as)
        preds  = logits.argmax(dim=1).cpu().numpy()
        y_true = labels.cpu().numpy()

    acc  = accuracy_score(y_true[test_idx],  preds[test_idx])
    f1   = f1_score(y_true[test_idx],        preds[test_idx], average='binary')
    prec = precision_score(y_true[test_idx], preds[test_idx], average='binary', zero_division=0)
    rec  = recall_score(y_true[test_idx],    preds[test_idx], average='binary')

    print(f"\n📊 Test Results (train={train_ratio}):")
    print(f"  Accuracy : {acc:.4f}")
    print(f"  F1       : {f1:.4f}")
    print(f"  Precision: {prec:.4f}")
    print(f"  Recall   : {rec:.4f}")

    return {'acc': acc, 'f1': f1, 'precision': prec, 'recall': rec}

