def run_experiment_fast(hin, dataset_name, train_ratio=0.8, epochs=50, lr=0.005, batch_size=512):
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    print(f"\n{'='*50}")
    print(f"Dataset: {dataset_name} | Train ratio: {train_ratio} | Device: {device}")
    print('='*50)

    news_feat, creator_feat, subject_feat, adj_ca, adj_as, labels = prepare_tensors(hin)

    # adj_ca is (N_creators, N_articles) — transpose to (N_articles, N_creators)
    adj_ac = adj_ca.t()   # (N_articles, N_creators)

    n = len(labels)
    indices = np.arange(n)
    train_idx, temp_idx = train_test_split(
        indices, train_size=train_ratio, stratify=labels.numpy(), random_state=42
    )
    val_idx, test_idx = train_test_split(
        temp_idx, test_size=0.5, stratify=labels.numpy()[temp_idx], random_state=42
    )

    model = HGAT(
        dim_news    = news_feat.size(1),
        dim_creator = creator_feat.size(1),
        dim_subject = subject_feat.size(1),
        hidden_dim  = 32,
        n_classes   = 2
    ).to(device)

    optimizer = torch.optim.Adam(model.parameters(), lr=lr, weight_decay=5e-4)
    criterion = nn.CrossEntropyLoss()

    best_val_acc = 0
    best_state   = None

    for epoch in range(1, epochs + 1):
        model.train()
        optimizer.zero_grad()

        # Sample batch from article indices
        batch = np.random.choice(train_idx, size=min(batch_size, len(train_idx)), replace=False)

        # Index rows (articles) correctly
        news_batch    = news_feat[batch, :]   # (batch, dim_news)
        adj_ac_batch  = adj_ac[batch, :]      # (batch, N_creators)
        adj_as_batch  = adj_as[batch, :]      # (batch, N_subjects)

        # Model expects adj_ca as (N_creators, N_articles) so transpose back
        logits = model(news_batch, creator_feat, subject_feat,
                       adj_ac_batch.t(), adj_as_batch)
        loss   = criterion(logits, labels[batch])
        loss.backward()
        optimizer.step()

        if epoch % 5 == 0:
            model.eval()
            with torch.no_grad():
                val_sample    = np.random.choice(val_idx, size=min(300, len(val_idx)), replace=False)
                news_val      = news_feat[val_sample, :]
                adj_ac_val    = adj_ac[val_sample, :]
                adj_as_val    = adj_as[val_sample, :]

                val_logits = model(news_val, creator_feat, subject_feat,
                                   adj_ac_val.t(), adj_as_val)
                preds   = val_logits.argmax(dim=1).cpu().numpy()
                val_acc = accuracy_score(labels.numpy()[val_sample], preds)

            if val_acc > best_val_acc:
                best_val_acc = val_acc
                best_state   = {k: v.clone() for k, v in model.state_dict().items()}

            print(f"  Epoch {epoch:3d} | Loss: {loss.item():.4f} | Val Acc: {val_acc:.4f}")

    if best_state:
        model.load_state_dict(best_state)

    # Test
    model.eval()
    all_preds  = []
    test_array = np.array(test_idx)

    with torch.no_grad():
        for i in range(0, len(test_array), batch_size):
            batch      = test_array[i:i+batch_size]
            news_b     = news_feat[batch, :]
            adj_ac_b   = adj_ac[batch, :]
            adj_as_b   = adj_as[batch, :]
            logits     = model(news_b, creator_feat, subject_feat,
                               adj_ac_b.t(), adj_as_b)
            all_preds.append(logits.argmax(dim=1).cpu().numpy())

    preds  = np.concatenate(all_preds)
    y_true = labels.numpy()[test_idx]

    acc  = accuracy_score(y_true,  preds)
    f1   = f1_score(y_true,        preds, average='binary')
    prec = precision_score(y_true, preds, average='binary', zero_division=0)
    rec  = recall_score(y_true,    preds, average='binary')

    print(f"\n📊 Test Results (train={train_ratio}):")
    print(f"  Accuracy : {acc:.4f}")
    print(f"  F1       : {f1:.4f}")
    print(f"  Precision: {prec:.4f}")
    print(f"  Recall   : {rec:.4f}")

    return {'acc': acc, 'f1': f1, 'precision': prec, 'recall': rec}

