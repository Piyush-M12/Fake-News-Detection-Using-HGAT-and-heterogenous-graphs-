import torch
import torch.nn as nn
import torch.nn.functional as F

class NodeLevelAttention(nn.Module):
    def __init__(self, neighbor_dim, out_dim):
        super().__init__()
        self.W = nn.Linear(neighbor_dim, out_dim, bias=False)

    def forward(self, h_neighbors, adj):
        h_n     = self.W(h_neighbors)
        row_sum = adj.sum(dim=1, keepdim=True).clamp(min=1e-8)
        return F.elu(torch.mm(adj / row_sum, h_n))

class SchemaLevelAttention(nn.Module):
    def __init__(self, dim):
        super().__init__()
        self.score = nn.Linear(dim * 2, 1)

    def forward(self, anchor, views):
        w = F.softmax(
            torch.cat([self.score(torch.cat([anchor, v], dim=1)) for v in views], dim=1),
            dim=1
        )
        return (torch.stack(views, dim=2) * w.unsqueeze(1)).sum(dim=2)

class HGATEmbedder(nn.Module):
    def __init__(self, dim_news, dim_creator, dim_subject, hidden_dim=64):
        super().__init__()
        self.proj_news    = nn.Linear(dim_news,    hidden_dim, bias=False)
        self.attn_creator = NodeLevelAttention(dim_creator, hidden_dim)
        self.attn_subject = NodeLevelAttention(dim_subject, hidden_dim)
        self.schema       = SchemaLevelAttention(hidden_dim)

    def forward(self, h_news, h_creator, h_subject, adj_ca, adj_as):
        adj_ac       = adj_ca.t()
        news_proj    = F.elu(self.proj_news(h_news))
        creator_repr = self.attn_creator(h_creator, adj_ac)
        subject_repr = self.attn_subject(h_subject, adj_as)
        return self.schema(news_proj, [creator_repr, subject_repr])

class TemporalHGAT(nn.Module):
    def __init__(self, hidden_dim=64, lstm_hidden=64, dropout=0.4):
        super().__init__()
        self.lstm = nn.LSTM(hidden_dim, lstm_hidden, batch_first=True)
        self.head = nn.Sequential(
            nn.Dropout(dropout),
            nn.Linear(lstm_hidden, 32),
            nn.ReLU(),
            nn.Linear(32, 2)
        )

    def forward(self, x):          # (batch, 3, hidden_dim)
        _, (h, _) = self.lstm(x)
        return self.head(h[-1])

