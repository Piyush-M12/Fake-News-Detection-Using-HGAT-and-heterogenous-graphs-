import scipy.sparse as sp

def sparse_to_dense(sp_mat, device):
    return torch.tensor(sp_mat.toarray().astype(np.float32), device=device)

def train_snapshot_embedder(hin, snap_id, train_mask_global,
                             hidden_dim=64, epochs=80, lr=0.005):
    """
    Trains the HGAT embedder ONLY on articles that are:
      (a) in snapshot snap_id  AND
      (b) in the global training split

    Then embeds ALL articles in that snapshot (train + test) using the
    trained (frozen) embedder — no weight updates from test articles.
    """
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    snap_mask        = hin['snapshot'] == snap_id
    snap_idx_all     = np.where(snap_mask)[0]                # all articles in snapshot
    snap_train_idx   = np.where(snap_mask & train_mask_global)[0]   # train-only subset

    name = ['Early', 'Middle', 'Late'][snap_id]
    print(f"    [{name}] total={len(snap_idx_all)}, train={len(snap_train_idx)}")

    if len(snap_train_idx) == 0:
        print(f"    [{name}] ⚠️  No training articles — using zeros")
        hidden_embs = torch.zeros(len(snap_idx_all), hidden_dim)
        return hidden_embs, snap_idx_all

    # ── Build features for ALL snapshot articles (transform only) ───────────
    news_all = torch.tensor(
        hin['news_features'][snap_idx_all].toarray(), dtype=torch.float32, device=device
    )
    adj_as_all = sparse_to_dense(hin['adj_as'][snap_idx_all, :], device)

    df_snap_all = hin['df'].iloc[snap_idx_all]

    # Creator subset: only creators seen in this snapshot's TRAIN articles
    df_snap_train   = hin['df'].iloc[snap_train_idx]
    train_creator_ids = np.unique(df_snap_train['creator_id'].values)
    global_to_local   = {g: l for l, g in enumerate(train_creator_ids)}

    creator_t = torch.tensor(
        hin['creator_features'][train_creator_ids].toarray(),
        dtype=torch.float32, device=device
    )
    subject_t = torch.tensor(hin['subject_features'], dtype=torch.float32, device=device)

    # Remap creator IDs for all snapshot articles (unseen → creator 0 as fallback)
    local_ids_all = np.array([
        global_to_local.get(cid, 0)
        for cid in df_snap_all['creator_id'].values
    ])
    n_local = len(train_creator_ids)
    adj_ca_all = torch.zeros(n_local, len(snap_idx_all), device=device)
    for art_local, cr_local in enumerate(local_ids_all):
        adj_ca_all[cr_local, art_local] = 1.0

    # ── Build features/adj for TRAINING articles only ───────────────────────
    # Map snap_train_idx positions to positions within snap_idx_all
    snap_idx_all_list   = list(snap_idx_all)
    train_positions_in_snap = [snap_idx_all_list.index(i) for i in snap_train_idx]

    news_tr   = news_all[train_positions_in_snap]
    adj_ca_tr = adj_ca_all[:, train_positions_in_snap]
    adj_as_tr = adj_as_all[train_positions_in_snap]

    # Local labels for training articles
    labels_tr = torch.tensor(
        hin['labels'][snap_train_idx], dtype=torch.long, device=device
    )

    # ── Build model ──────────────────────────────────────────────────────────
    embedder = HGATEmbedder(
        dim_news    = news_tr.shape[1],
        dim_creator = creator_t.shape[1],
        dim_subject = subject_t.shape[1],
        hidden_dim  = hidden_dim
    ).to(device)
    for p in embedder.parameters():
        if p.dim() > 1:
            nn.init.xavier_uniform_(p)

    n_fake = labels_tr.sum().item()
    n_real = len(labels_tr) - n_fake
    w          = torch.tensor([1.0, n_real / max(n_fake, 1)], device=device)
    classifier = nn.Sequential(nn.Linear(hidden_dim, 2)).to(device)
    optimizer  = torch.optim.Adam(
        list(embedder.parameters()) + list(classifier.parameters()),
        lr=lr, weight_decay=5e-4
    )
    criterion  = nn.CrossEntropyLoss(weight=w)

    best_loss, best_state = float('inf'), None

    for epoch in range(1, epochs + 1):
        embedder.train(); classifier.train()
        optimizer.zero_grad()

        emb  = embedder(news_tr, creator_t, subject_t, adj_ca_tr, adj_as_tr)
        if torch.isnan(emb).any():
            continue
        loss = criterion(classifier(emb), labels_tr)
        if torch.isnan(loss):
            continue
        loss.backward()
        torch.nn.utils.clip_grad_norm_(
            list(embedder.parameters()) + list(classifier.parameters()), max_norm=1.0
        )
        optimizer.step()

        if loss.item() < best_loss:
            best_loss  = loss.item()
            best_state = {k: v.clone() for k, v in embedder.state_dict().items()}

        if epoch % 20 == 0:
            print(f"    [{name}] Epoch {epoch:3d} | Loss: {loss.item():.4f}")

    # ── Embed ALL snapshot articles with frozen best embedder ────────────────
    if best_state:
        embedder.load_state_dict(best_state)
    embedder.eval()
    with torch.no_grad():
        all_embs = embedder(news_all, creator_t, subject_t, adj_ca_all, adj_as_all)

    if torch.isnan(all_embs).any():
        print(f"    [{name}] ⚠️  NaN in final embeddings — using zeros")
        all_embs = torch.zeros(len(snap_idx_all), hidden_dim)

    print(f"    [{name}] ✅ Done | best loss: {best_loss:.4f}")
    return all_embs.cpu(), snap_idx_all


def build_temporal_embeddings(hin, dataset_name, hidden_dim=64, epochs=80, lr=0.005):
    print(f"\n{'='*55}")
    print(f"Building temporal embeddings: {dataset_name}")
    print('='*55)
    n             = hin['n_articles']
    result        = np.zeros((n, 3, hidden_dim), dtype=np.float32)
    train_mask    = hin['global_train_mask']

    for snap_id in [0, 1, 2]:
        emb, idx = train_snapshot_embedder(
            hin, snap_id, train_mask, hidden_dim, epochs, lr
        )
        result[idx, snap_id, :] = emb.numpy()

    print(f"✅ Temporal embeddings shape: {result.shape}")
    return result

