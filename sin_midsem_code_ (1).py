from sklearn.metrics import accuracy_score, f1_score, precision_score, recall_score

def run_temporal_experiment(hin, dataset_name, temporal_embs,
                             train_ratio=0.8, lstm_epochs=100, lr=0.005,
                             hidden_dim=64):
    """
    Uses hin['global_train_mask'] for the train/test split — the SAME split
    used when fitting the TF-IDF vectorizers. This guarantees no leakage
    between feature engineering, embedding, and evaluation.

    The train_ratio parameter here is used only to sub-sample the training
    set for the ablation study (matching the paper's 20/40/60/80% sweep).
    """
    print(f"\n── LSTM | {dataset_name} | train={int(train_ratio*100)}% ──")
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')

    labels           = hin['labels']
    global_train_idx = np.where(hin['global_train_mask'])[0]
    global_test_idx  = np.where(~hin['global_train_mask'])[0]

    # Sub-sample training set for the sweep while keeping test fixed
    if train_ratio < 0.8:
        sub_size  = int(len(global_train_idx) * (train_ratio / 0.8))
        sub_size  = max(sub_size, 10)
        rng       = np.random.default_rng(42)
        train_idx = rng.choice(global_train_idx, size=sub_size, replace=False)
    else:
        train_idx = global_train_idx

    # Val split from remaining training data
    remaining = np.setdiff1d(global_train_idx, train_idx)
    if len(remaining) > 0:
        val_idx = remaining
    else:
        # If nothing left (tiny datasets), just use train as val
        val_idx = train_idx

    test_idx = global_test_idx

    X = torch.tensor(temporal_embs, dtype=torch.float32)
    y = torch.tensor(labels,        dtype=torch.long)

    X_tr = X[train_idx].to(device);  y_tr = y[train_idx].to(device)
    X_va = X[val_idx].to(device);    y_va = y[val_idx].to(device)
    X_te = X[test_idx].to(device);   y_te = y[test_idx].to(device)

    n_fake = y_tr.sum().item()
    n_real = len(y_tr) - n_fake
    w      = torch.tensor([1.0, n_real / max(n_fake, 1)], device=device)

    model     = TemporalHGAT(hidden_dim=hidden_dim).to(device)
    optimizer = torch.optim.Adam(model.parameters(), lr=lr, weight_decay=5e-4)
    criterion = nn.CrossEntropyLoss(weight=w)
    scheduler = torch.optim.lr_scheduler.StepLR(optimizer, step_size=30, gamma=0.5)

    best_val_f1, best_state = 0.0, None

    for epoch in range(1, lstm_epochs + 1):
        model.train()
        optimizer.zero_grad()
        criterion(model(X_tr), y_tr).backward()
        optimizer.step()
        scheduler.step()

        if epoch % 10 == 0:
            model.eval()
            with torch.no_grad():
                preds  = model(X_va).argmax(1).cpu().numpy()
            val_f1 = f1_score(y_va.cpu().numpy(), preds, average='binary', zero_division=0)
            val_ac = accuracy_score(y_va.cpu().numpy(), preds)
            if val_f1 > best_val_f1:
                best_val_f1 = val_f1
                best_state  = {k: v.clone() for k, v in model.state_dict().items()}
            print(f"  Epoch {epoch:3d} | Val Acc: {val_ac:.4f} | Val F1: {val_f1:.4f}")

    if best_state:
        model.load_state_dict(best_state)

    model.eval()
    with torch.no_grad():
        preds  = model(X_te).argmax(1).cpu().numpy()
    y_true = y_te.cpu().numpy()

    res = {
        'acc'      : accuracy_score(y_true, preds),
        'f1'       : f1_score(y_true, preds, average='binary', zero_division=0),
        'precision': precision_score(y_true, preds, average='binary', zero_division=0),
        'recall'   : recall_score(y_true, preds, average='binary', zero_division=0),
    }
    print(f"\n📊 Test | Acc: {res['acc']:.4f} | F1: {res['f1']:.4f} | "
          f"Prec: {res['precision']:.4f} | Rec: {res['recall']:.4f}")
    return res

