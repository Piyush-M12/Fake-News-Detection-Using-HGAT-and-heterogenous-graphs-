def build_hin(real_df, fake_df, dataset_name="politifact"):
    """
    Build a News-HIN from real/fake CSVs.
    Nodes: News Articles, Creators (extracted from URL domain), Subjects (inferred from title keywords)
    Links: creator→article, article→subject
    """
    # Add labels
    real_df = real_df.copy()
    fake_df = fake_df.copy()
    real_df['label'] = 0  # real
    fake_df['label'] = 1  # fake

    # Combine
    df = pd.concat([real_df, fake_df], ignore_index=True)
    df['title'] = df['title'].fillna('')
    df['news_url'] = df['news_url'].fillna('')

    # ── News Article Features (TF-IDF on title) ──────────────────
    vectorizer_news = TfidfVectorizer(max_features=3000, stop_words='english')
    news_features = vectorizer_news.fit_transform(df['title'])  # (N_articles, 3000)

    # ── Creator nodes (domain of URL as proxy for creator) ─────────
    def extract_domain(url):
        try:
            from urllib.parse import urlparse
            domain = urlparse(url if url.startswith('http') else 'http://'+url).netloc
            return domain if domain else 'unknown'
        except:
            return 'unknown'

    df['creator'] = df['news_url'].apply(extract_domain)
    creators = df['creator'].unique().tolist()
    creator2id = {c: i for i, c in enumerate(creators)}
    df['creator_id'] = df['creator'].map(creator2id)

    # Creator features: TF-IDF on URL text
    vectorizer_creator = TfidfVectorizer(max_features=500, analyzer='char_wb', ngram_range=(2,4))
    creator_texts = [c for c in creators]
    creator_features = vectorizer_creator.fit_transform(creator_texts)

    # ── Subject nodes (simple keyword binning from title) ──────────
    # Use top TF-IDF terms per article as subject tags (simplified)
    vectorizer_subject = TfidfVectorizer(max_features=100, stop_words='english')
    subject_matrix = vectorizer_subject.fit_transform(df['title'])
    # Each article's top subject = argmax of its TF-IDF row
    top_subject_ids = np.array(subject_matrix.argmax(axis=1)).flatten()
    df['subject_id'] = top_subject_ids
    n_subjects = 100
    subject_features = np.eye(n_subjects, dtype=np.float32)  # identity (one-hot)

    # ── Adjacency: creator→article ─────────────────────────────────
    n_articles = len(df)
    n_creators = len(creators)
    row_c = df['creator_id'].values
    col_a = np.arange(n_articles)
    data_c = np.ones(n_articles)
    # Shape: (n_creators, n_articles)
    adj_creator_article = sp.csr_matrix(
        (data_c, (row_c, col_a)), shape=(n_creators, n_articles)
    )

    # ── Adjacency: article→subject ─────────────────────────────────
    row_a2 = np.arange(n_articles)
    col_s = df['subject_id'].values
    data_s = np.ones(n_articles)
    # Shape: (n_articles, n_subjects)
    adj_article_subject = sp.csr_matrix(
        (data_s, (row_a2, col_s)), shape=(n_articles, n_subjects)
    )

    labels = df['label'].values
    print(f"[{dataset_name}] Articles: {n_articles}, Creators: {n_creators}, Subjects: {n_subjects}")
    print(f"  Real: {(labels==0).sum()}, Fake: {(labels==1).sum()}")

    return {
        'news_features': news_features,        # scipy sparse (N_articles, 3000)
        'creator_features': creator_features,  # scipy sparse (N_creators, 500)
        'subject_features': subject_features,  # numpy (100, 100)
        'adj_ca': adj_creator_article,         # (N_creators, N_articles)
        'adj_as': adj_article_subject,         # (N_articles, 100)
        'labels': labels,
        'n_articles': n_articles,
        'n_creators': n_creators,
        'n_subjects': n_subjects,
        'df': df
    }

