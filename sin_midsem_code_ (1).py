def add_temporal_snapshots(hin, dataset_name):
    """
    Assigns snapshot labels (0=Early, 1=Middle, 2=Late) using ONLY the
    global_train_mask ordering — test articles are binned by their
    position but the bin boundaries come from training data quantiles only.

    This prevents the sort-key from carrying future label information
    into the snapshot boundaries.
    """
    from urllib.parse import urlparse
    df           = hin['df']
    train_mask   = hin['global_train_mask']
    timestamp_col = None

    for col in ['publish_date', 'date', 'published', 'timestamp']:
        if col in df.columns:
            timestamp_col = col
            break

    if timestamp_col:
        ts = pd.to_datetime(df[timestamp_col], errors='coerce')
        df['_creator'] = df['news_url'].apply(
            lambda u: urlparse(u if str(u).startswith('http') else 'http://'+str(u)).netloc
        )
        # Impute only within training articles to avoid leakage
        train_ts = ts[train_mask]
        group_median = (df.loc[train_mask]
                          .groupby('_creator')
                          .apply(lambda g: pd.to_datetime(ts[g.index], errors='coerce').median()))
        for i in df.index[~train_mask & ts.isna()]:
            creator = df.at[i, '_creator']
            ts.at[i] = group_median.get(creator, train_ts.median())
        ts = ts.fillna(train_ts.median())
        sort_key = ts.rank(method='first')
        print(f"[{dataset_name}] Using timestamp column: '{timestamp_col}'")
    else:
        print(f"[{dataset_name}] ⚠️  No timestamp — using row order as proxy")
        sort_key = pd.Series(np.arange(len(df)), index=df.index)

    # Compute bin edges from TRAIN only, apply to all
    train_sort  = sort_key[train_mask]
    q33, q67    = np.percentile(train_sort, [33.33, 66.67])
    snapshots   = np.where(sort_key <= q33, 0, np.where(sort_key <= q67, 1, 2))

    hin['snapshot'] = snapshots
    counts = {i: (snapshots == i).sum() for i in [0, 1, 2]}
    print(f"[{dataset_name}] Snapshots → Early: {counts[0]}, Middle: {counts[1]}, Late: {counts[2]}")

