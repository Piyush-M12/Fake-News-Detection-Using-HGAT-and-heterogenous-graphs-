import torch
import torch.nn as nn
import torch.nn.functional as F

class NodeLevelAttention(nn.Module):
    """Aggregates neighbors with a type-specific projection."""
    def __init__(self, target_dim, neighbor_dim, out_dim):
        super().__init__()
        self.W_target   = nn.Linear(target_dim,   out_dim, bias=False)
        self.W_neighbor = nn.Linear(neighbor_dim, out_dim, bias=False)

    def forward(self, h_target, h_neighbors, adj):
        """
        h_target:    (N_target, target_dim)
        h_neighbors: (N_neighbor, neighbor_dim)
        adj:         tensor (N_target, N_neighbor)
        Returns:     (N_target, out_dim)
        """
        h_n = self.W_neighbor(h_neighbors)   # (N_neighbor, out_dim)

        # Normalize adjacency rows
        row_sum = adj.sum(dim=1, keepdim=True).clamp(min=1e-8)
        adj_norm = adj / row_sum              # (N_target, N_neighbor)

        # Aggregate
        out = torch.mm(adj_norm, h_n)         # (N_target, out_dim)
        return F.elu(out)


class SchemaLevelAttention(nn.Module):
    def __init__(self, schema_dim):
        super().__init__()
        self.score = nn.Linear(schema_dim * 2, 1)

    def forward(self, target_repr, schema_nodes):
        scores = []
        for sn in schema_nodes:
            combined = torch.cat([target_repr, sn], dim=1)
            scores.append(self.score(combined))
        weights = F.softmax(torch.cat(scores, dim=1), dim=1)  # (N, K)
        schema_stack = torch.stack(schema_nodes, dim=2)        # (N, D, K)
        return (schema_stack * weights.unsqueeze(1)).sum(dim=2)


class HGAT(nn.Module):
    def __init__(self, dim_news, dim_creator, dim_subject, hidden_dim=64, n_classes=2):
        super().__init__()
        self.hidden_dim = hidden_dim

        # Each attention uses the correct input dimensions
        self.attn_self    = NodeLevelAttention(dim_news,    dim_news,    hidden_dim)
        self.attn_creator = NodeLevelAttention(dim_news,    dim_creator, hidden_dim)
        self.attn_subject = NodeLevelAttention(dim_news,    dim_subject, hidden_dim)

        self.schema_attn = SchemaLevelAttention(hidden_dim)

        self.classifier = nn.Sequential(
            nn.Linear(hidden_dim, 32),
            nn.ReLU(),
            nn.Dropout(0.5),
            nn.Linear(32, n_classes)
        )

    def forward(self, h_news, h_creator, h_subject, adj_ca, adj_as):
        """
        adj_ca: (N_articles, N_creators)  — needs transpose of original
        adj_as: (N_articles, N_subjects)
        """
        N = h_news.size(0)

        # Self schema node: article attends to itself (identity adjacency)
        schema_N = self.attn_self(h_news, h_news,
                                  torch.eye(N, device=h_news.device))

        # Creator schema node: adj_ca is (N_creators, N_articles), transpose -> (N_articles, N_creators)
        schema_C = self.attn_creator(h_news, h_creator, adj_ca.t())

        # Subject schema node: adj_as is (N_articles, N_subjects)
        schema_S = self.attn_subject(h_news, h_subject, adj_as)

        # Schema-level fusion
        r_ni = self.schema_attn(schema_N, [schema_N, schema_C, schema_S])

        return self.classifier(r_ni)

