def build_hin_leakage_free(real_df, fake_df, dataset_name="politifact",
                            base_train_ratio=0.8, random_state=42):
    """
    Builds HIN with ALL vectorizers fitted ONLY on the training split.
    Returns hin dict with an additional 'global_train_mask' boolean array.

    Key fix: TF-IDF for news titles, creator char-ngrams, and subject bins
    are all fit exclusively on the training articles, then *transformed* on
    the full dataset. Test articles therefore never influence the feature space.
    """
    real_df = real_df.copy(); fake_df = fake_df.copy()
    real_df['label'] = 0;     fake_df['label'] = 1
    df = pd.concat([real_df, fake_df], ignore_index=True)
    df['title']    = df['title'].fillna('')
    df['news_url'] = df['news_url'].fillna('')

    # ── Global split FIRST — before any fitting ─────────────────────────────
    n      = len(df)
    labels = df['label'].values
    all_idx = np.arange(n)
    train_idx, test_idx = train_test_split(
        all_idx, train_size=base_train_ratio,
        stratify=labels, random_state=random_state
    )
    train_mask = np.zeros(n, dtype=bool)
    train_mask[train_idx] = True

    train_titles = df['title'].iloc[train_idx]

    # ── News features: fit on TRAIN only ────────────────────────────────────
    vec_news = TfidfVectorizer(max_features=3000, stop_words='english')
    vec_news.fit(train_titles)
    news_features = vec_news.transform(df['title'])          # (N, 3000)

    # ── Creator nodes ───────────────────────────────────────────────────────
    def extract_domain(url):
        try:
            domain = urlparse(url if str(url).startswith('http') else 'http://'+str(url)).netloc
            return domain if domain else 'unknown'
        except:
            return 'unknown'

    df['creator'] = df['news_url'].apply(extract_domain)
    # Build creator vocab from TRAIN only
    train_creators = df['creator'].iloc[train_idx].unique().tolist()
    # Unknown creator for unseen test domains
    if 'unknown' not in train_creators:
        train_creators.append('unknown')
    creator2id = {c: i for i, c in enumerate(train_creators)}
    df['creator_id'] = df['creator'].map(creator2id).fillna(creator2id['unknown']).astype(int)

    vec_creator = TfidfVectorizer(max_features=500, analyzer='char_wb', ngram_range=(2, 4))
    vec_creator.fit(train_creators)
    creator_features = vec_creator.transform(train_creators)  # (N_train_creators, 500)

    # ── Subject nodes: top-100 TF-IDF terms, vocab from TRAIN only ─────────
    vec_subject = TfidfVectorizer(max_features=100, stop_words='english')
    vec_subject.fit(train_titles)
    subject_matrix   = vec_subject.transform(df['title'])
    top_subject_ids  = np.array(subject_matrix.argmax(axis=1)).flatten()
    df['subject_id'] = top_subject_ids
    n_subjects       = 100
    subject_features = np.eye(n_subjects, dtype=np.float32)

    # ── Adjacency matrices ──────────────────────────────────────────────────
    n_articles = n
    n_creators = len(train_creators)

    row_c = df['creator_id'].values
    col_a = np.arange(n_articles)
    adj_creator_article = sp.csr_matrix(
        (np.ones(n_articles), (row_c, col_a)),
        shape=(n_creators, n_articles)
    )

    row_a2 = np.arange(n_articles)
    col_s  = df['subject_id'].values
    adj_article_subject = sp.csr_matrix(
        (np.ones(n_articles), (row_a2, col_s)),
        shape=(n_articles, n_subjects)
    )

    print(f"[{dataset_name}] Articles: {n_articles}, Train: {train_mask.sum()}, "
          f"Test: {(~train_mask).sum()}")
    print(f"  Real: {(labels==0).sum()}, Fake: {(labels==1).sum()}")
    print(f"  Creators (train vocab): {n_creators}")

    return {
        'news_features'  : news_features,
        'creator_features': creator_features,
        'subject_features': subject_features,
        'adj_ca'         : adj_creator_article,
        'adj_as'         : adj_article_subject,
        'labels'         : labels,
        'n_articles'     : n_articles,
        'n_creators'     : n_creators,
        'n_subjects'     : n_subjects,
        'df'             : df,
        'global_train_mask': train_mask,   # NEW — used by temporal cells
    }

